function explanation(document, diagnostic, code) {
    if (code === 13 && /^[:;]/.test(document.getText(diagnostic.range))) {
        return {title: '冒号或分号处的句间距提醒',
            cause: '大写缩写后的冒号或分号可能触发句末间距规则，但这里未必是句子结束。',
            recommendation: '标题、列表引导或句中说明通常忽略本行；不要仅为消除提示而批量插入 \\@。'};
    }
    const entry = messages[code];
    if (!entry) return {title: '尚未收录的检查规则', cause: '当前中文说明未覆盖这个警告编号。',
        recommendation: '请在“问题”面板核对原始诊断，不要直接全文接受。'};
    const [title, cause, recommendation] = entry;
    const alternative = code === 11 ? /\\[cl]?dots/.exec(diagnostic.message)?.[0]
        : code === 35 ? /`(.+)'/.exec(diagnostic.message)?.[1] : undefined;
    return {title, cause, recommendation: recommendation + (alternative ? ` 本处建议：${alternative}。` : '')};
}
